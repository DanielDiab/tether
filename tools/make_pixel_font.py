def main() -> None:
    pygame.init()
    os.makedirs(OUT, exist_ok=True)
    charset = "".join(GLYPHS.keys())
    sheet = pygame.Surface((CELL_W * len(charset), CELL_H), pygame.SRCALPHA)
    sheet.fill((0, 0, 0, 0))
    white = (255, 255, 255, 255)
    for index, char in enumerate(charset):
        ox = index * CELL_W
        for row, line in enumerate(GLYPHS[char]):
            for col, pixel in enumerate(line):
                if pixel == "#":
                    sheet.set_at((ox + col, row), white)
    png = os.path.join(OUT, "font_8x8.png")
    pygame.image.save(sheet, png)
    meta = {
        "charset": charset,
        "cell_w": CELL_W, "cell_h": CELL_H,
        "glyph_w": GLYPH_W, "glyph_h": GLYPH_H,
        "advance": ADVANCE,
        "base_size": CELL_H
    }
    with open(os.path.join(OUT, "font_8x8.json"), "w", encoding="utf-8") as meta_file:
        json.dump(meta, meta_file, indent=4)
    print(f"font_8x8.png: {sheet.get_width()}x{sheet.get_height()} "
          f"({len(charset)} glifos, avance {ADVANCE}px)")
    pygame.quit()


if __name__ == "__main__":
    main()
